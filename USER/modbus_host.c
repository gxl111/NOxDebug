	{
		MODH_Send03H (SlaveAddr, _reg, _num);
		xTimerStart( MODH_Timer, portMAX_DELAY);
				
		while (1)
		{
			MODH_Poll();
		
			if (time1 ==1)		
			{
				break;
			}
			
			if (g_tModH.fAck03H > 0)
			{
				break;
			}
		}
		
		if (g_tModH.fAck03H > 0)
		{
            
			break;
		}
	}
